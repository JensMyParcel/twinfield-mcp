import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { CatalogGenerator } from '../../../codegen/catalog-generator.js';
import { SERVICES } from '../../../codegen/service-registry.js';
import { SoapProtocol } from '../../../src/catalog/catalog-types.js';
import { SOAP_CATALOG } from '../../../src/catalog/soap-catalog.generated.js';

const VENDOR = fileURLToPath(new URL('../../../vendor/twinfield', import.meta.url));
const COMMITTED = fileURLToPath(
  new URL('../../../src/catalog/soap-catalog.generated.ts', import.meta.url),
);

const generator = new CatalogGenerator(VENDOR);
const catalog = generator.catalog();

describe('CatalogGenerator on the vendored Twinfield specs', () => {
  it('writes exactly the committed generated catalog', () => {
    expect(generator.source()).toBe(readFileSync(COMMITTED, 'utf8'));
  });

  it('builds the same catalog that the server loads', () => {
    expect(JSON.parse(JSON.stringify(catalog))).toEqual(SOAP_CATALOG);
  });

  it('offers 67 operations', () => {
    expect(catalog.operations).toHaveLength(67);
  });

  it('gives every operation a unique tool name of at most 64 snake case characters', () => {
    const tools = catalog.operations.map((operation) => operation.tool);

    expect(new Set(tools).size).toBe(tools.length);
    for (const tool of tools) {
      expect(tool).toMatch(/^[a-z][a-z0-9_]*$/);
      expect(tool.length).toBeLessThanOrEqual(64);
    }
  });

  it('marks the generated file as generated', () => {
    expect(generator.source()).toMatch(
      /^\/\/ Generated by `npm run generate` from vendor\/twinfield\./,
    );
  });
});

describe('CatalogGenerator with a subset of the registry', () => {
  it('reads only the WSDL of an ASMX service, which has no separate schema files', () => {
    const versions = SERVICES.filter((service) => service.prefix === 'versions');

    const subset = new CatalogGenerator(VENDOR, versions).catalog();

    expect(subset.operations.map((operation) => operation.tool)).toEqual([
      'versions_get_twinfield_version',
    ]);
    expect(subset.types).toHaveLength(1);
  });

  it('reads the schema files of a WCF service by their case-insensitive service name', () => {
    const bankBook = SERVICES.filter((service) => service.prefix === 'bank_book');

    const subset = new CatalogGenerator(VENDOR, bankBook).catalog();

    expect(subset.operations.every((op) => op.protocol === SoapProtocol.commandQuery)).toBe(true);
    expect(subset.operations).toHaveLength(6);
  });

  it('fails on a registry entry whose WSDL file is not vendored', () => {
    const missing = [{ ...SERVICES[0]!, wsdlFile: 'missing.svc.wsdl' }];

    expect(() => new CatalogGenerator(VENDOR, missing).catalog()).toThrow(/ENOENT/);
  });

  it('builds an empty catalog for an empty registry', () => {
    expect(new CatalogGenerator(VENDOR, []).catalog()).toEqual({ types: [], operations: [] });
  });
});
